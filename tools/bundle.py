#!/usr/bin/env python3
"""Bundle a design into one self-contained .scad file.

MakerWorld's Parametric Model Maker (and some other customizers) want a
single .scad file. This script inlines every `use <...>` / `include <...>`
that points at a file inside this repo (recursively, each file once) and
writes build/<name>_bundled.scad.

  python3 tools/bundle.py joycon/garmin-grip/joycon_garmin_grip.scad
  python3 tools/bundle.py --all          # every design .scad (<controller>/<design>/*.scad, except fit tests)

Notes
- `use <lib>` imports modules/functions; when inlining, top-level calls in
  the library are dropped but its module/function definitions and variable
  assignments are kept (library modules can depend on them). Keep library
  constant names distinctive (e.g. JC_*) so they can't clash with design
  variables. `include <lib>` is inlined verbatim.
- Customizer parameters must come first in the output, so the design's own
  file is emitted first and library code is appended after it.
- import("...svg") is NOT inlined: upload the SVG next to the bundled file
  (and fix the path to a bare filename), or set logo = false.
- Libraries outside the repo (e.g. BOSL2) are left as-is.
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIRECTIVE = re.compile(r'^\s*(use|include)\s*<([^>]+)>\s*;?\s*$', re.M)


def strip_top_level_statements(code: str) -> str:
    """Mimic `use`: keep module/function definitions and top-level variable
    assignments (library modules may rely on them); drop everything else,
    such as demo calls at the bottom of a library file."""
    # Blank out comments and strings (keeping offsets) so braces/semicolons
    # inside them don't confuse the scanner.
    def blank(m):
        return re.sub(r'[^\n]', ' ', m.group(0))
    nc = re.sub(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"', blank, code, flags=re.S)
    keep, depth, seg_start = [], 0, 0
    for i, ch in enumerate(nc):
        if ch in '{([':
            depth += 1
        elif ch in '})]':
            depth -= 1
        if depth == 0 and (ch == ';' or ch == '}'):
            stmt_nc = nc[seg_start:i + 1].strip()
            # a module/function body ends with '}' but a block statement
            # like `if (x) { ... }` might be followed by more; fine either way
            if re.match(r'(module|function)\b', stmt_nc) or \
               re.match(r'\$?[A-Za-z_]\w*\s*=(?!=)', stmt_nc):
                keep.append(code[seg_start:i + 1].strip('\n'))
            seg_start = i + 1
    return '\n'.join(keep) + '\n'


def bundle(path: pathlib.Path) -> str:
    seen = set()
    libs = []

    def resolve(src: pathlib.Path, text: str, top: bool) -> str:
        def repl(m):
            kind, target = m.group(1), m.group(2)
            lib = (src.parent / target).resolve()
            if not lib.is_file() or ROOT not in lib.parents:
                return m.group(0)  # external library: leave it alone
            if lib in seen:
                return f'// (already bundled: {target})'
            seen.add(lib)
            body = lib.read_text()
            body = resolve(lib, body, False)
            if kind == 'use':
                body = strip_top_level_statements(body)
            rel = lib.relative_to(ROOT).as_posix()
            libs.append(f'// ===== bundled from {rel} ({kind}) =====\n{body}')
            return f'// {kind} <{target}>  -> bundled below'
        return DIRECTIVE.sub(repl, text)

    main = resolve(path, path.read_text(), True)
    header = (f'// Bundled single-file version of {path.relative_to(ROOT).as_posix()}\n'
              f'// Generated by tools/bundle.py - edit the source files, not this one.\n'
              f'// Any import()ed files (e.g. the logo SVG) must be uploaded alongside.\n\n')
    # Asset paths (e.g. the logo SVG) become bare file names, so the bundle
    # works with the asset uploaded next to it.
    main = re.sub(r'"(?:\.\./)+assets/', '"', main)
    return header + main.rstrip() + '\n\n' + '\n\n'.join(libs)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('files', nargs='*')
    ap.add_argument('--all', action='store_true', help='bundle every design .scad (<controller>/<design>/*.scad, except fit tests)')
    a = ap.parse_args()
    files = [pathlib.Path(f).resolve() for f in a.files]
    if a.all:
        files += [p for p in sorted(ROOT.glob('*/*/*.scad'))
                  if p.parts[-3] not in ('lib', 'tools', 'build') and not p.name.endswith('_bundled.scad')]
    if not files:
        ap.error('give a .scad file or --all')
    for f in files:
        (ROOT / 'build').mkdir(exist_ok=True)
        out = ROOT / 'build' / (f.stem + '_bundled.scad')
        out.write_text(bundle(f))
        print(f'{f.relative_to(ROOT)} -> {out.relative_to(ROOT)}')


if __name__ == '__main__':
    sys.exit(main())
